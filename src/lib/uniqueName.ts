/** 새로 만드는 것의 **이름 규칙 — 여기 하나뿐이다** (사용자 지시 2026-08-27).
 *
 *  ★★*"번호는 붙여줘. 탭, 그룹, 씬, 캐릭터 등등 전부 일관되게."*
 *    예전에는 같은 반복문이 **세 군데에 복사**돼 있었고(워크스페이스·탭·그룹), 씬과 덱 카드에는
 *    아예 없어서 「새 스타일」이 끝없이 쌓였다. 씬만 또 규칙이 달라서(`씬 1`·`씬 2`) 층마다
 *    이름이 다른 꼴로 붙었다.
 *
 *  규칙: **첫 번째는 이름 그대로, 겹치면 뒤에 2·3…**
 *
 *      새 씬 그룹 · 새 씬 그룹 2 · 새 씬 그룹 3
 *      새 씬      · 새 씬 2      · 새 씬 3
 *
 *  ★비교는 **글자 그대로**다 — 다듬거나 대소문자를 무시하지 않는다. 사용자가 지은 이름과
 *    우리가 지은 이름이 같은 규칙으로 서야 하고, 「새 씬」과 「새  씬」은 다른 이름이다.
 *  ★`used` 에 무엇을 넣을지가 곧 **겹침의 범위**다. 부르는 쪽이 정한다 —
 *    탭은 워크스페이스 안에서, 씬은 **그 그룹 안에서** 겹치지 않으면 된다.
 */
export function uniqueName(base: string, used: Iterable<string>): string {
  const taken = used instanceof Set ? used : new Set(used);
  if (!taken.has(base)) return base;
  for (let i = 2; ; i++) {
    const nm = `${base} ${i}`;
    if (!taken.has(nm)) return nm;
  }
}
