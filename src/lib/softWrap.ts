/** 글 상자가 **화면에서만** 쓰는 글자 바꾸기 — 접힐 자리를 쉼표 뒤 하나만 남긴다.
 *
 *  ★★칩은 통째로 접혀 태그가 두 줄에 걸칠 일이 없는데, 글 상자는 빈칸·붙임표면 어디서든
 *    접혀 `looking at viewer` 가 둘로, `close-up` 이 `close-` / `up` 으로 쪼개졌다
 *    (사용자 지적 2026-08-22). CSS 로는 못 막는다 — `word-break: keep-all`·`overflow-wrap`·
 *    `text-wrap` 을 여섯 판 다 대 봤지만 전부 쪼개졌다 (실측).
 *  ★**길이가 안 바뀌는 치환**이다 (한 글자를 한 글자로). 그래서 커서 자리·자동완성의 자리
 *    계산이 전부 그대로 맞는다. 폭도 같다 — 보통 빈칸 3.64px 대 NBSP 3.64px,
 *    보통 붙임표 4.52px 대 U+2011 4.52px (실측).
 *  ★★**밖으로 나가는 글은 반드시 `toStore` 를 지난다.** 이 글자들이 저장이나 NAI 로 새면 안 된다.
 *
 *  ★★여기 따로 둔 까닭: 글 상자(`blocks/BlockBody`)가 만들어 놓은 모양을 **자동완성
 *    (`blocks/TagSuggest`)이 읽어야** 한다. 자동완성은 화면의 날것 값을 읽어 낱말을 자르는데,
 *    되돌리지 않고 읽으면 `close‑`(U+2011)로 사전을 뒤져 **아무것도 안 걸린다** —
 *    사용자가 `-` 를 치는 순간 자동완성이 멈춘 것이 그것이다 (2026-08-22).
 *    글 상자에서 내보내면 두 파일이 서로를 부르게 되므로(자동완성은 글 상자가 쓰는 훅이다)
 *    양쪽이 함께 보는 자리를 하나 둔다. */

/** 안 깨지는 빈칸 */
export const NBSP = " ";
/** 안 깨지는 붙임표 */
export const NBHY = "‑";

/** 고칠 때의 글 — 접힐 자리를 **쉼표 뒤 하나만** 남긴다 */
export const toEdit = (t: string): string =>
  t.replace(/[ -]/g, (m, i: number) => (m === "-" ? NBHY : t[i - 1] === "," ? " " : NBSP));

/** 밖으로 나가는 글 — **반드시 되돌린다** */
export const toStore = (t: string): string =>
  t.replace(/ /g, " ").replace(/‑/g, "-");
