/** **글자를 맺는 중인가** — 한글·일본어·중국어 입력기의 조합 상태.
 *
 *  ★★왜 필요한가 (사용자 지적 2026-08-25, 채팅 입력칸에서 잡았다): 한글을 치면 마지막
 *    음절이 **조합 중**인 채로 Enter 가 온다. 그 Enter 를 「확정·전송」으로 받으면
 *      · 보낸 글에서 끝 음절이 잘리고,
 *      · 입력칸을 비운 **뒤에** 그 음절이 맺히면서 다시 들어와 칸이 안 비운다.
 *    채팅에서는 뒤엣것 때문에 단추가 「보내기」에 머물러 **멈출 방법이 없어졌다.**
 *
 *  ★조합 중의 Enter 는 **글자를 맺는 것**이지 명령이 아니다. 그래서 거른다.
 *  ★`isComposing` 을 안 주는 옛 브라우저는 `keyCode 229` 로 같은 것을 말한다 — 둘 다 본다.
 *  ★창구를 하나로 둔다: 자리마다 따로 적으면 새로 만드는 입력칸이 또 빠뜨린다. */
export function composing(e: { nativeEvent: KeyboardEvent }): boolean {
  return e.nativeEvent.isComposing || e.nativeEvent.keyCode === 229;
}
